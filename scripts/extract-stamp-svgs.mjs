/**
 * Regenerates the stamp SVG components from the live target site.
 *
 *   node scripts/extract-stamp-svgs.mjs
 *
 * The three stamp layers (perforated frame, printed lettering, cast shadow) are inline
 * SVG in francobollimontilessini.com's server-rendered homepage, not standalone assets.
 * This fetches that HTML, lifts one instance of each, and writes them into a single
 * `StampDefs.tsx` — keeping ~39KB of path data out of any editor or agent context, and
 * out of the rendered page more than once.
 *
 * `StampFrame`/`StampPrint`/`StampShadow` reference that sheet with `<use>`. They are
 * hand-written and this script does not touch them; only the geometry is generated.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "https://www.francobollimontilessini.com/";
const OUT = path.join(
  ROOT,
  "src/components/sites/francobollimontilessini-d2eadb58/root-8a5edab2/stamp",
);

const LAYERS = [
  { name: "frame", marker: "gsap:frame/source" },
  { name: "stamp", marker: "gsap:stamp/source" },
  { name: "shadow", marker: "gsap:shadow/source" },
];

/** HTML attribute names that JSX spells differently. */
const ATTR_MAP = {
  class: "className",
  "xml:space": "xmlSpace",
  "color-interpolation-filters": "colorInterpolationFilters",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stop-color": "stopColor",
  "stop-opacity": "stopOpacity",
};

/** The full `<svg>…</svg>` whose opening tag carries `marker`. */
function extract(html, marker) {
  const at = html.indexOf(marker);
  if (at === -1) throw new Error(`marker not found: ${marker}`);
  const start = html.lastIndexOf("<svg", at);
  if (start === -1) throw new Error(`no <svg> before ${marker}`);

  let depth = 0;
  let i = start;
  for (;;) {
    const open = html.indexOf("<svg", i);
    const close = html.indexOf("</svg>", i);
    if (close === -1) throw new Error(`unterminated svg for ${marker}`);
    if (open !== -1 && open < close) {
      depth++;
      i = open + 4;
    } else {
      depth--;
      i = close + 6;
      if (depth === 0) return html.slice(start, i);
    }
  }
}

const inner = (svg) => svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");

function toJsx(markup) {
  let out = markup;
  for (const [from, to] of Object.entries(ATTR_MAP)) {
    out = out.replaceAll(new RegExp(`(\\s)${from}=`, "g"), `$1${to}=`);
  }
  // The target's Flip bookkeeping; our transition measures its own geometry.
  return out.replace(/\sdata-flip-id="[^"]*"/g, "");
}

const BANNER = `// Extracted from francobollimontilessini.com by scripts/extract-stamp-svgs.mjs.
// Generated file — re-run the script rather than editing the path data by hand.`;

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`fetch failed: ${response.status}`);
const html = await response.text();

const svg = Object.fromEntries(
  LAYERS.map(({ name, marker }) => [name, toJsx(inner(extract(html, marker)))]),
);

fs.mkdirSync(OUT, { recursive: true });

const groups = svg.stamp.match(/<g>[\s\S]*?<\/g>/g);
if (!groups || groups.length !== 2) {
  throw new Error(`expected 2 groups in the print layer, got ${groups?.length ?? 0}`);
}

const filter = svg.shadow.match(/<filter[\s\S]*?<\/filter>/)[0].replace('id="blur"', 'id="ml-stamp-blur"');
const shadowPath = svg.shadow
  .match(/<path[^>]*d="[^"]*"[^>]*>/)[0]
  .replace("<path ", '<path id="ml-stamp-shadow" ');

// One sheet of geometry for the whole document. The three layers are ~23KB of path data,
// and a stamp is drawn five times over on the index and once per gallery slide; inlining
// each copy put 167KB of duplicated `d=` into a 190KB homepage, all of which React then
// had to hydrate before the cover would answer a tap. `<use>` costs one empty element.
fs.writeFileSync(
  path.join(OUT, "StampDefs.tsx"),
  `${BANNER}

/**
 * Every stamp layer's geometry, defined once for the whole document.
 *
 * Mounted once, at the root, above anything that draws a stamp. The layers below are
 * referenced by \`StampFrame\`, \`StampPrint\` and \`StampShadow\`, which are hand-written
 * \`<use>\` wrappers and are *not* regenerated by this script.
 */
export function StampDefs() {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      // Out of flow and out of the accessibility tree, but not \`display:none\` — a
      // referenced element inside a hidden subtree still resolves, and this keeps the
      // sheet from ever being laid out or painted on its own account.
      className="pointer-events-none absolute h-0 w-0 overflow-hidden"
    >
      <defs>
        <g id="ml-stamp-frame">
          ${svg.frame}
        </g>

        <g id="ml-stamp-print">
          ${groups[0]}
          ${groups[1]}
        </g>

        ${filter}
        ${shadowPath}
      </defs>
    </svg>
  );
}
`,
);

for (const file of fs.readdirSync(OUT)) {
  console.log(`${file}: ${fs.statSync(path.join(OUT, file)).size}B`);
}
